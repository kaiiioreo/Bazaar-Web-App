import { useState } from 'react'
import Card from '../ui/Card'
import Button from '../ui/Button'
import { refreshSentiment } from '../../api/admin'
import { timeAgo } from '../../utils/format'

// Review sentiment summary with a Refresh button (SummarizeReviewSentiment for the Admin).
// `initial` is the dashboard stats: { sentimentSummary, sentimentByAI, sentimentUpdatedAt, aiEnabled }.
export default function SentimentCard({ initial }) {
  const [info, setInfo] = useState(initial)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')

  const refresh = async () => {
    setBusy(true)
    setError('')
    try {
      setInfo(await refreshSentiment())
    } catch (err) {
      setError(err.message)
    } finally {
      setBusy(false)
    }
  }

  const source = info.sentimentByAI
    ? `Generated by AI from the most recent reviews · updated ${timeAgo(info.sentimentUpdatedAt)}`
    : info.aiEnabled
      ? 'Quick summary from star ratings. Click Refresh for the AI summary.'
      : 'Quick summary from star ratings (AI is not connected).'

  return (
    <Card tone="accent" className="mb-6">
      <div className="mb-2 flex flex-wrap items-center justify-between gap-3">
        <h2 className="font-semibold text-ink">Review sentiment summary</h2>
        <Button
          size="sm"
          variant="secondary"
          onClick={refresh}
          disabled={busy}
          aria-label="Refresh review sentiment summary"
        >
          <span aria-hidden="true" className={busy ? 'inline-block animate-spin' : 'inline-block'}>
            ↻
          </span>
          {busy ? 'Refreshing…' : 'Refresh'}
        </Button>
      </div>
      <p className={`text-ink transition-opacity ${busy ? 'opacity-50' : ''}`} aria-live="polite">
        {info.sentimentSummary}
      </p>
      <p className="mt-2 text-xs text-muted">{source}</p>
      {error && (
        <p className="mt-2 text-sm text-danger" role="alert">
          {error}
        </p>
      )}
    </Card>
  )
}
