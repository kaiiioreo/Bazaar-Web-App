import { Link } from 'react-router-dom'
import StatCard from '../../components/admin/StatCard'
import LoadState from '../../components/common/LoadState'
import useApi from '../../hooks/useApi'
import { getStats } from '../../api/admin'

// ViewReportsAndAnalytics()
export default function Dashboard() {
  const { data: stats, loading, error, reload } = useApi(() => getStats(), [])

  return (
    <div>
      <h2 className="mb-6 text-2xl font-bold">Dashboard</h2>
      {loading || error ? (
        <LoadState loading={loading} error={error} onRetry={reload} />
      ) : (
        <>
          <div className="mb-8 grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
            <StatCard label="Active Vendors" value={stats.activeVendors} />
            <StatCard label="Pending Applications" value={stats.pendingApplications} />
            <StatCard label="Registered Customers" value={stats.totalCustomers} />
            <StatCard label="Upcoming Events" value={stats.upcomingEvents} />
          </div>
          <div className="mb-8 grid grid-cols-1 gap-4 sm:grid-cols-2">
            <StatCard label="Average Review Rating" value={stats.totalReviews ? `${stats.averageRating} ★` : '–'} />
            <StatCard label="Reviews Flagged by AI" value={stats.flaggedReviews} />
          </div>
          <div className="rounded-lg bg-white p-6 shadow">
            <h3 className="mb-2 font-semibold">Review Sentiment Summary</h3>
            <p className="text-slate-600">{stats.sentimentSummary}</p>
            <p className="mt-2 text-xs text-slate-400">Generated by AI from the {stats.totalReviews} most recent reviews.</p>
          </div>
          {(stats.pendingApplications > 0 || stats.flaggedReviews > 0) && (
            <div className="mt-6 flex flex-wrap gap-3 text-sm">
              {stats.pendingApplications > 0 && (
                <Link to="/admin/applications" className="rounded bg-blue-600 px-4 py-2 text-white hover:bg-blue-700">
                  Review {stats.pendingApplications} pending application{stats.pendingApplications > 1 ? 's' : ''}
                </Link>
              )}
              {stats.flaggedReviews > 0 && (
                <Link to="/admin/reviews" className="rounded border border-slate-300 bg-white px-4 py-2 hover:bg-slate-50">
                  Moderate {stats.flaggedReviews} flagged review{stats.flaggedReviews > 1 ? 's' : ''}
                </Link>
              )}
            </div>
          )}
        </>
      )}
    </div>
  )
}
